import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

import {
  MAX_WORD_LENGTH,
  MIN_WORD_LENGTH,
  normalizeBundledWordPayload,
  partitionAnswerPools,
} from '../src/domain/words.ts';

const ROOT = resolve(import.meta.dirname, '..');
const WORD_ROOT = resolve(ROOT, 'public/word-lists/bundled');
const OUTPUT = resolve(
  ROOT,
  'supabase/migrations/20260724221000_amordle_authoritative_word_catalog.sql',
);

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function sqlString(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function sqlTextArray(values) {
  return `array[${values.map(sqlString).join(',')}]::text[]`;
}

function canonicalCatalogHash({ revision, wordLength, casual, standard, expert, validGuesses }) {
  return sha256(
    [
      revision,
      String(wordLength),
      casual.join('\n'),
      standard.join('\n'),
      expert.join('\n'),
      validGuesses.join('\n'),
    ].join('\n--amordle-catalog-boundary--\n'),
  );
}

const records = [];
for (let wordLength = MIN_WORD_LENGTH; wordLength <= MAX_WORD_LENGTH; wordLength += 1) {
  const path = resolve(WORD_ROOT, `words_length_${wordLength}.json`);
  const source = await readFile(path);
  const payload = normalizeBundledWordPayload(JSON.parse(source.toString('utf8')));
  if (payload.wordLength !== wordLength) {
    throw new Error(`Catalog length mismatch for ${path}.`);
  }
  const pools = partitionAnswerPools(payload.answers);
  const validGuesses = [...payload.validGuesses];
  if (!pools.expert.every((word) => validGuesses.includes(word))) {
    throw new Error(`Expert answers are not contained in valid guesses for length ${wordLength}.`);
  }
  const record = {
    revision: payload.revision,
    wordLength,
    casual: [...pools.casual],
    standard: [...pools.standard],
    expert: [...pools.expert],
    validGuesses,
    sourceSha256: sha256(source),
  };
  records.push({
    ...record,
    derivedSha256: canonicalCatalogHash(record),
  });
}

const revisions = new Set(records.map((record) => record.revision));
if (revisions.size !== 1) {
  throw new Error('Every authoritative word length must use the same bundled revision.');
}

const rows = records
  .map(
    (record) => `(
  ${sqlString(record.revision)},
  ${record.wordLength},
  ${sqlTextArray(record.casual)},
  ${sqlTextArray(record.standard)},
  ${sqlTextArray(record.expert)},
  ${sqlTextArray(record.validGuesses)},
  ${sqlString(record.sourceSha256)},
  ${sqlString(record.derivedSha256)}
)`,
  )
  .join(',\n');

const sql = `-- Amordle authoritative multiplayer word catalog.
--
-- Generated by scripts/generate-authoritative-word-catalog.mjs from the
-- immutable bundled revision. Browser roles have no access to this schema,
-- table, or its validation helpers.

create extension if not exists pgcrypto with schema extensions;
create schema if not exists brrrdle_private;
revoke all on schema brrrdle_private from public, anon, authenticated;

create table if not exists brrrdle_private.amordle_word_catalogs (
  revision text not null,
  word_length integer not null check (word_length between 2 and 35),
  casual_answers text[] not null,
  standard_answers text[] not null,
  expert_answers text[] not null,
  valid_guesses text[] not null,
  source_sha256 text not null check (source_sha256 ~ '^[0-9a-f]{64}$'),
  derived_sha256 text not null check (derived_sha256 ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now(),
  primary key (revision, word_length)
);

create or replace function brrrdle_private.amordle_catalog_hash(
  p_revision text,
  p_word_length integer,
  p_casual text[],
  p_standard text[],
  p_expert text[],
  p_valid text[]
)
returns text
language sql
immutable
set search_path = ''
as $$
  select encode(
    extensions.digest(
      convert_to(
        concat_ws(
          E'\\n--amordle-catalog-boundary--\\n',
          p_revision,
          p_word_length::text,
          array_to_string(p_casual, E'\\n'),
          array_to_string(p_standard, E'\\n'),
          array_to_string(p_expert, E'\\n'),
          array_to_string(p_valid, E'\\n')
        ),
        'UTF8'
      ),
      'sha256'
    ),
    'hex'
  )
$$;

create or replace function brrrdle_private.validate_amordle_word_catalog()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_word text;
begin
  if cardinality(new.expert_answers) < 1
    or cardinality(new.casual_answers) <> greatest(1, ceil(cardinality(new.expert_answers) * 0.35)::integer)
    or cardinality(new.standard_answers) <> greatest(cardinality(new.casual_answers), ceil(cardinality(new.expert_answers) * 0.70)::integer)
    or cardinality(new.casual_answers) <> cardinality(array(select distinct value from unnest(new.casual_answers) value))
    or cardinality(new.standard_answers) <> cardinality(array(select distinct value from unnest(new.standard_answers) value))
    or cardinality(new.expert_answers) <> cardinality(array(select distinct value from unnest(new.expert_answers) value))
    or cardinality(new.valid_guesses) <> cardinality(array(select distinct value from unnest(new.valid_guesses) value))
    or not new.casual_answers <@ new.standard_answers
    or not new.standard_answers <@ new.expert_answers
    or not new.expert_answers <@ new.valid_guesses
  then
    raise exception 'Invalid nested authoritative word catalog.' using errcode = '23514';
  end if;

  foreach v_word in array new.valid_guesses loop
    if v_word !~ ('^[a-z]{' || new.word_length::text || '}$') then
      raise exception 'Authoritative catalog contains an invalid word.' using errcode = '23514';
    end if;
  end loop;

  if new.derived_sha256 is distinct from brrrdle_private.amordle_catalog_hash(
    new.revision,
    new.word_length,
    new.casual_answers,
    new.standard_answers,
    new.expert_answers,
    new.valid_guesses
  ) then
    raise exception 'Authoritative catalog checksum mismatch.' using errcode = '23514';
  end if;
  return new;
end;
$$;

create or replace function brrrdle_private.reject_amordle_word_catalog_mutation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'Authoritative word catalog rows are immutable.' using errcode = '55000';
end;
$$;

drop trigger if exists validate_amordle_word_catalog_trigger
  on brrrdle_private.amordle_word_catalogs;
create trigger validate_amordle_word_catalog_trigger
  before insert on brrrdle_private.amordle_word_catalogs
  for each row execute function brrrdle_private.validate_amordle_word_catalog();

drop trigger if exists reject_amordle_word_catalog_mutation_trigger
  on brrrdle_private.amordle_word_catalogs;
create trigger reject_amordle_word_catalog_mutation_trigger
  before update or delete on brrrdle_private.amordle_word_catalogs
  for each row execute function brrrdle_private.reject_amordle_word_catalog_mutation();

insert into brrrdle_private.amordle_word_catalogs (
  revision,
  word_length,
  casual_answers,
  standard_answers,
  expert_answers,
  valid_guesses,
  source_sha256,
  derived_sha256
) values
${rows};

revoke all on table brrrdle_private.amordle_word_catalogs
  from public, anon, authenticated;
revoke all on function brrrdle_private.amordle_catalog_hash(text, integer, text[], text[], text[], text[])
  from public, anon, authenticated;
revoke all on function brrrdle_private.validate_amordle_word_catalog()
  from public, anon, authenticated;
revoke all on function brrrdle_private.reject_amordle_word_catalog_mutation()
  from public, anon, authenticated;

comment on table brrrdle_private.amordle_word_catalogs
  is 'Immutable 2-35 letter server-only multiplayer catalog generated from bundled revision ${[...revisions][0]}.';
`;

await writeFile(OUTPUT, sql);
console.log(
  JSON.stringify({
    output: OUTPUT,
    revision: [...revisions][0],
    lengths: records.length,
    answers: records.reduce((sum, record) => sum + record.expert.length, 0),
    validGuesses: records.reduce((sum, record) => sum + record.validGuesses.length, 0),
    bytes: Buffer.byteLength(sql),
  }),
);
